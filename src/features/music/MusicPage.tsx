// Music page — manage YouTube playlists for the in-app player.
// Paste a playlist URL, name it, then play/stop/delete from the list.
import { useState, type FormEvent } from 'react'
import { Card } from '../../components/ui/Card'
import { Button } from '../../components/ui/Button'
import { EmptyState } from '../../components/ui/EmptyState'
import { Modal } from '../../components/ui/Modal'
import { useData } from '../../app/providers'
import { db } from '../../db/app-db'
import { useMusicPlayer } from '../../lib/music-player'
import { extractPlaylistIdLoose, isMixPlaylistId } from '../../lib/youtube'
import { isoNow } from '../../lib/utils'
import { cn } from '../../lib/utils'
import { filterActive } from '../../lib/filterActive'
import { v4 as uuid } from 'uuid'
import type { MusicPlaylist } from '../../domain/types'

/** Themed inline icons (no emoji affordances — spec §10.65). */
function PlayGlyph({ className }: { className?: string }) {
  return (
    <svg className={className} fill="currentColor" viewBox="0 0 24 24" aria-hidden="true">
      <path d="M8 5v14l11-7z" />
    </svg>
  )
}

function PauseGlyph({ className }: { className?: string }) {
  return (
    <svg className={className} fill="currentColor" viewBox="0 0 24 24" aria-hidden="true">
      <path d="M7 5h4v14H7zM13 5h4v14h-4z" />
    </svg>
  )
}

function MusicGlyph({ className }: { className?: string }) {
  return (
    <svg className={className} fill="none" stroke="currentColor" viewBox="0 0 24 24" strokeWidth={2} aria-hidden="true">
      <path strokeLinecap="round" strokeLinejoin="round" d="M9 18V5l12-2v13M9 18a3 3 0 11-6 0 3 3 0 016 0zM21 16a3 3 0 11-6 0 3 3 0 016 0z" />
    </svg>
  )
}

function EqualiserGlyph({ className, playing }: { className?: string; playing?: boolean }) {
  return (
    <svg className={className} fill="none" stroke="currentColor" viewBox="0 0 24 24" strokeWidth={2} aria-hidden="true">
      <path strokeLinecap="round" d={playing ? 'M4 10v4M8 7v10M12 4v16M16 7v10M20 10v4' : 'M4 12h3M10 12h3M16 12h3'} />
    </svg>
  )
}

function formatAddedAt(iso: string): string {
  const d = new Date(iso)
  if (isNaN(d.getTime())) return ''
  return d.toLocaleDateString(undefined, { day: 'numeric', month: 'short', year: 'numeric' })
}

export default function MusicPage() {
  const { data, loadData } = useData()
  const player = useMusicPlayer()
  const playlists = filterActive(data.musicPlaylists)

  const [addOpen, setAddOpen] = useState(false)
  const [urlInput, setUrlInput] = useState('')
  const [nameInput, setNameInput] = useState('')
  const [error, setError] = useState('')
  const [saving, setSaving] = useState(false)
  const [deleteTarget, setDeleteTarget] = useState<MusicPlaylist | null>(null)

  async function handleAdd(e: FormEvent) {
    e.preventDefault()
    setError('')
    const id = extractPlaylistIdLoose(urlInput)
    if (!id) {
      setError('That does not look like a YouTube playlist link. Paste a link containing "list=…".')
      return
    }
    if (isMixPlaylistId(id)) {
      setError('Mix/radio playlists are generated by YouTube and cannot be saved. Use a normal playlist link.')
      return
    }
    setSaving(true)
    try {
      const now = isoNow()
      await db.musicPlaylists.put({
        id: uuid(),
        name: nameInput.trim() || 'My playlist',
        youtubePlaylistId: id,
        createdAt: now,
        updatedAt: now,
      })
      await loadData()
      setAddOpen(false)
      setUrlInput('')
      setNameInput('')
    } finally {
      setSaving(false)
    }
  }

  async function handleDelete() {
    if (!deleteTarget) return
    const row = deleteTarget
    setDeleteTarget(null)
    if (player.activePlaylistId === row.id) player.stop()
    await db.musicPlaylists.put({ ...row, deletedAt: isoNow(), updatedAt: isoNow() })
    await loadData()
  }

  const blocked = player.stalled || player.engineFailed

  return (
    <div className="mx-auto max-w-3xl space-y-4">
      <div className="flex items-center justify-between">
        <div>
          <h1 className="text-xl font-bold text-slate-800 dark:text-slate-100">Music</h1>
          <p className="text-sm text-slate-500 dark:text-slate-400">
            Save YouTube playlists and play them on repeat while you study.
          </p>
        </div>
        <Button onClick={() => setAddOpen(true)}>+ Add playlist</Button>
      </div>

      {blocked && (
        <div className="flex items-center justify-between gap-3 rounded-lg border border-amber-300 bg-amber-50 px-4 py-2.5 text-sm text-amber-800 dark:border-amber-800/60 dark:bg-amber-900/30 dark:text-amber-200">
          <span>
            {player.engineFailed
              ? 'The music engine could not load — check your connection or ad-blocker settings.'
              : 'Playback was blocked by the browser. Retry the playlist.'}
          </span>
          <Button size="sm" onClick={player.retry}>Retry</Button>
        </div>
      )}

      {playlists.length === 0 ? (
        <Card>
          <EmptyState
            icon={<MusicGlyph className="h-8 w-8 text-slate-400" />}
            title="No playlists yet"
            description="Paste a YouTube playlist link to build your study soundtrack. It plays in order, on loop, right inside Momentum."
          />
        </Card>
      ) : (
        <div className="space-y-2">
          {playlists.map((p) => {
            const isActive = player.activePlaylistId === p.id
            return (
              <Card key={p.id} className={cn(isActive && 'ring-2 ring-primary-500')}>
                <div className="flex flex-wrap items-center gap-3">
                  <span
                    className={cn(
                      'flex h-9 w-9 shrink-0 items-center justify-center rounded-full',
                      isActive
                        ? 'bg-primary-100 text-primary-700 dark:bg-primary-900/50 dark:text-primary-300'
                        : 'bg-slate-100 text-slate-500 dark:bg-slate-700 dark:text-slate-300',
                    )}
                    aria-hidden="true"
                  >
                    <EqualiserGlyph className="h-4 w-4" playing={isActive && player.isPlaying} />
                  </span>
                  <div className="min-w-0 flex-1">
                    <p className="truncate text-sm font-semibold text-slate-800 dark:text-slate-100">
                      {p.name}
                      {isActive && (
                        <span className="ml-2 rounded-full bg-primary-100 px-2 py-0.5 text-[10px] font-bold uppercase tracking-wide text-primary-700 dark:bg-primary-900/40 dark:text-primary-300">
                          {blocked ? 'Blocked' : player.isPlaying ? 'Playing' : 'Paused'}
                        </span>
                      )}
                    </p>
                    <p className="truncate text-xs text-slate-500 dark:text-slate-400">
                      {p.trackCount ? `${p.trackCount} tracks · ` : ''}Added {formatAddedAt(p.createdAt)} · list: {p.youtubePlaylistId}
                    </p>
                  </div>
                  {isActive ? (
                    <Button variant="secondary" size="sm" onClick={player.toggle}>
                      {player.isPlaying ? <PauseGlyph className="h-3.5 w-3.5" /> : <PlayGlyph className="h-3.5 w-3.5" />}
                      {player.isPlaying ? 'Pause' : 'Play'}
                    </Button>
                  ) : (
                    <Button size="sm" onClick={() => player.playPlaylist(p.id)}>
                      <PlayGlyph className="h-3.5 w-3.5" />
                      Play
                    </Button>
                  )}
                  <Button variant="ghost" size="sm" onClick={() => setDeleteTarget(p)}>
                    Delete
                  </Button>
                </div>
              </Card>
            )
          })}
        </div>
      )}

      <Modal open={addOpen} onClose={() => setAddOpen(false)} title="Add a YouTube playlist">
        <form onSubmit={handleAdd} className="space-y-3">
          <div>
            <label htmlFor="music-url" className="label">Playlist link</label>
            <input
              id="music-url"
              className="input w-full"
              placeholder="https://www.youtube.com/playlist?list=…"
              value={urlInput}
              onChange={(e) => setUrlInput(e.target.value)}
              autoFocus
            />
          </div>
          <div>
            <label htmlFor="music-name" className="label">Name <span className="font-normal text-slate-400">(optional)</span></label>
            <input
              id="music-name"
              className="input w-full"
              placeholder="e.g. Lo-fi study mix"
              value={nameInput}
              onChange={(e) => setNameInput(e.target.value)}
            />
          </div>
          {error && <p className="text-sm text-red-600 dark:text-red-400">{error}</p>}
          <div className="flex justify-end gap-2 border-t border-slate-200 pt-3 dark:border-slate-700">
            <Button type="button" variant="secondary" size="sm" onClick={() => setAddOpen(false)}>
              Cancel
            </Button>
            <Button type="submit" size="sm" disabled={saving || !urlInput.trim()}>
              {saving ? 'Saving…' : 'Save playlist'}
            </Button>
          </div>
        </form>
      </Modal>

      <Modal open={deleteTarget !== null} onClose={() => setDeleteTarget(null)} title="Delete playlist">
        <p className="text-sm text-slate-600 dark:text-slate-300">
          Remove <strong>{deleteTarget?.name}</strong> from your music list? The playlist stays on YouTube — only the
          entry here is removed.
        </p>
        <div className="mt-4 flex justify-end gap-2 border-t border-slate-200 pt-3 dark:border-slate-700">
          <Button variant="secondary" size="sm" onClick={() => setDeleteTarget(null)}>Cancel</Button>
          <Button variant="danger" size="sm" onClick={handleDelete}>Delete</Button>
        </div>
      </Modal>
    </div>
  )
}